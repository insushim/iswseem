export async function POST(request: NextRequest) {
  try {
    const apiKey = process.env.GEMINI_API_KEY;

    if (!apiKey) {
      console.error("GEMINI_API_KEY is not set");
      return NextResponse.json(
        { error: "API 설정 오류입니다." },
        { status: 500 },
      );
    }

    const genAI = new GoogleGenerativeAI(apiKey);
    const { image, sideImage, age } = await request.json();

    if (!image) {
      return NextResponse.json(
        { error: "이미지가 필요합니다." },
        { status: 400 },
      );
    }

    // base64 데이터 추출
    const base64Match = image.match(/^data:(.+);base64,(.+)$/);
    if (!base64Match) {
      return NextResponse.json(
        { error: "이미지 형식이 올바르지 않습니다." },
        { status: 400 },
      );
    }

    const mimeType = base64Match[1];
    const base64Data = base64Match[2];
    const hasSideImage = !!sideImage;

    const model = genAI.getGenerativeModel({
      model: "gemini-2.5-flash",
    });

    const prompt = buildPrompt(age ? Number(age) : undefined, hasSideImage);

    const contentParts: any[] = [
      prompt,
      {
        inlineData: {
          mimeType: mimeType,
          data: base64Data,
        },
      },
    ];

    if (sideImage) {
      const sideMatch = sideImage.match(/^data:(.+);base64,(.+)$/);
      if (sideMatch) {
        contentParts.push({
          inlineData: {
            mimeType: sideMatch[1],
            data: sideMatch[2],
          },
        });
      }
    }

    const result = await model.generateContent(contentParts);

    const response = await result.response;
    const text = response.text();

    return NextResponse.json({ result: text });
  } catch (error: unknown) {
    console.error("Gemini API error:", error);

    const errorMessage = error instanceof Error ? error.message : String(error);
    const errorStr = JSON.stringify(
      error,
      Object.getOwnPropertyNames(error || {}),
    );
    console.error("Error details:", errorStr);

    if (errorMessage.includes("API_KEY") || errorMessage.includes("API key")) {
      return NextResponse.json(
        { error: "API 키가 유효하지 않습니다." },
        { status: 500 },
      );
    }
    if (errorMessage.includes("SAFETY") || errorMessage.includes("blocked")) {
      return NextResponse.json(
        { error: "이미지를 분석할 수 없습니다. 다른 사진을 시도해주세요." },
        { status: 400 },
      );
    }
    if (
      errorMessage.includes("not valid") ||
      errorMessage.includes("invalid image")
    ) {
      return NextResponse.json(
        {
          error:
            "이미지가 너무 작거나 손상되었습니다. 다른 사진을 시도해주세요.",
        },
        { status: 400 },
      );
    }
    if (
      errorMessage.includes("quota") ||
      errorMessage.includes("rate") ||
      errorMessage.includes("429") ||
      errorMessage.includes("Resource")
    ) {
      return NextResponse.json(
        { error: "요청이 너무 많습니다. 1분 후 다시 시도해주세요." },
        { status: 429 },
      );
    }
    if (errorMessage.includes("not found") || errorMessage.includes("404")) {
      return NextResponse.json(
        { error: "API 모델을 찾을 수 없습니다." },
        { status: 500 },
      );
    }

    return NextResponse.json(
      { error: `분석 오류: ${errorMessage.slice(0, 100)}` },
      { status: 500 },
    );
  }
}
