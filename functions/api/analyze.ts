export const onRequestPost: PagesFunction<Env> = async (context) => {
  const { request, env } = context;

  try {
    const apiKey = env.GEMINI_API_KEY;
    if (!apiKey) {
      return new Response(JSON.stringify({ error: "API 설정 오류입니다." }), {
        status: 500,
        headers: { "Content-Type": "application/json" },
      });
    }

    const body: any = await request.json();
    const { image, sideImage, age } = body;

    if (!image) {
      return new Response(JSON.stringify({ error: "이미지가 필요합니다." }), {
        status: 400,
        headers: { "Content-Type": "application/json" },
      });
    }

    const base64Match = image.match(/^data:(.+);base64,(.+)$/);
    if (!base64Match) {
      return new Response(
        JSON.stringify({ error: "이미지 형식이 올바르지 않습니다." }),
        {
          status: 400,
          headers: { "Content-Type": "application/json" },
        },
      );
    }

    const mimeType = base64Match[1];
    const base64Data = base64Match[2];
    const hasSideImage = !!sideImage;
    const prompt = buildPrompt(age ? Number(age) : undefined, hasSideImage);

    const parts: any[] = [
      { text: prompt },
      {
        inline_data: {
          mime_type: mimeType,
          data: base64Data,
        },
      },
    ];

    if (sideImage) {
      const sideMatch = sideImage.match(/^data:(.+);base64,(.+)$/);
      if (sideMatch) {
        parts.push({
          inline_data: {
            mime_type: sideMatch[1],
            data: sideMatch[2],
          },
        });
      }
    }

    const geminiUrl = `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash:generateContent?key=${apiKey}`;

    const geminiResponse = await fetch(geminiUrl, {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        contents: [{ parts }],
      }),
    });

    if (!geminiResponse.ok) {
      const errText = await geminiResponse.text();
      console.error("Gemini API error:", errText);

      if (geminiResponse.status === 429) {
        return new Response(
          JSON.stringify({
            error: "요청이 너무 많습니다. 1분 후 다시 시도해주세요.",
          }),
          {
            status: 429,
            headers: { "Content-Type": "application/json" },
          },
        );
      }
      return new Response(
        JSON.stringify({ error: "분석 중 오류가 발생했습니다." }),
        {
          status: 500,
          headers: { "Content-Type": "application/json" },
        },
      );
    }

    const data: any = await geminiResponse.json();
    const text =
      data.candidates?.[0]?.content?.parts?.[0]?.text ||
      "분석 결과를 생성할 수 없습니다.";

    return new Response(JSON.stringify({ result: text }), {
      headers: { "Content-Type": "application/json" },
    });
  } catch (error: any) {
    console.error("Analyze error:", error);
    return new Response(
      JSON.stringify({ error: "분석 중 오류가 발생했습니다." }),
      {
        status: 500,
        headers: { "Content-Type": "application/json" },
      },
    );
  }
};
